"""Hidden cases for `expr`: one JSON object per line on stdout.

The evaluator here is deliberately NOT the shape of the reference (a recursive-descent parser over a position): it is a tokenizer
followed by precedence climbing over Python's unbounded integers, with an explicit range check after every single operation.
Run `python3 oracle.py --self` to check it against hand-computed values (the hand list is HAND below, worked out from the brief,
not by running this code).

Semantics (the brief): ASCII space (0x20) is the only whitespace; a literal is one or more ASCII digits (leading zeros allowed) and
must be <= 2**63-1 (so "-9223372036854775808" is an error, "-9223372036854775807-1" is the minimum); unary minus only (no unary
plus); every + - * / % result and every unary minus result must lie in [-2**63, 2**63-1] or the whole answer is Err; division
truncates toward zero, a % b = a - (a / b) * b (so MIN % -1 is 0, MIN / -1 is Err); division or modulo by zero is Err.
"""
import json, random, sys, threading
sys.setrecursionlimit(100000)
threading.stack_size(256 * 1024 * 1024)
LO, HI = -2**63, 2**63 - 1

class Bad(Exception):
    pass

def tokens(s):
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c == ' ':
            i += 1
        elif c in '0123456789' and c.isascii():
            j = i
            while j < len(s) and s[j] in '0123456789':
                j += 1
            n = int(s[i:j])
            if n > HI: raise Bad
            out.append(('n', n)); i = j
        elif c in '+-*/%()':
            out.append((c, None)); i += 1
        else:
            raise Bad
    return out

def tdiv(a, b):
    q = abs(a) // abs(b)
    return q if (a < 0) == (b < 0) else -q

def chk(v):
    if not (LO <= v <= HI): raise Bad
    return v

def apply(op, a, b):
    if op == '+': return chk(a + b)
    if op == '-': return chk(a - b)
    if op == '*': return chk(a * b)
    if b == 0: raise Bad
    q = tdiv(a, b)
    if op == '/': return chk(q)         # MIN / -1 does not fit
    return a - q * b                    # the remainder always fits, MIN % -1 == 0

PREC = {'+': 1, '-': 1, '*': 2, '/': 2, '%': 2}

def evaluate(s):
    """Returns an int or None (= Err)."""
    try:
        t = tokens(s)
        pos = [0]
        def peek(): return t[pos[0]][0] if pos[0] < len(t) else None
        def atom():
            k = peek()
            if k is None: raise Bad
            if k == 'n':
                v = t[pos[0]][1]; pos[0] += 1; return v
            if k == '-':
                pos[0] += 1
                return chk(-atom())
            if k == '(':
                pos[0] += 1
                v = climb(1)
                if peek() != ')': raise Bad
                pos[0] += 1
                return v
            raise Bad
        def climb(minp):
            lhs = atom()
            while peek() in PREC and PREC[peek()] >= minp:
                op = peek(); pos[0] += 1
                rhs = climb(PREC[op] + 1)       # left associative
                lhs = apply(op, lhs, rhs)
            return lhs
        v = climb(1)
        if pos[0] != len(t): raise Bad
        return v
    except Bad:
        return None

